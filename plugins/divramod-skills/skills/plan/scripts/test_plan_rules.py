import test_plan

SLUG = "0002-migrate-daily-tools"
HEAD = """---
type: Plan
schema: 1
id: 2
title: "migrate daily tools"
description: "x"
status: open
landing: auto
run: claude-opus-5-5 medium 1m
created: 2026-11-01
---

# Plan 0002: migrate daily tools

## Brief

In: x. Out: y. Must: z. Proof: w.

## Steps

| # | Step | Done when | Model | Effort | Window | Size | Status |
|---|---|---|---|---|---|---|---|
"""


class PlanRulesTest(unittest.TestCase):
    setUp, tearDown = test_plan.PlanTest.setUp, test_plan.PlanTest.tearDown
    run_plan, plan, write_plan = test_plan.PlanTest.run_plan, test_plan.PlanTest.plan, test_plan.PlanTest.write_plan

    def plan_with(self, *rows: str) -> None:
        self.write_plan(text=HEAD + "\n".join(rows) + "\n")
        self.plan("use", "2")

    def rules(self) -> list[str]:
        self.env_off()
        out = self.run_plan("check", "--json")
        return [p.rsplit("(", 1)[-1].rstrip(")") for p in json.loads(out.stdout)["problems"]
                if "plan-no-after-landing" in p or "plan-milestone-reason" in p]

    def env_off(self):
        patcher = mock.patch.dict(os.environ, {"HAL2_CLI_RECORDS": str(self.root / "none")})
        patcher.start()
        self.addCleanup(patcher.stop)

    def test_an_open_after_the_landing_step_fails_the_check_and_names_uat(self):
        self.plan_with("| 1 | build | `cargo test` | sonnet | high | 1m | 10k | done |",
                       "| 2 | install | after the landing: `x --version` works | sonnet | high | 1m | 10k | |")
        self.assertEqual(self.rules(), ["plan-no-after-landing"])
        text = self.run_plan("check", "--json").stdout
        self.assertIn("uat.md", text)
        self.assertIn("Auto: yes", text)

    def test_a_done_after_the_landing_step_and_a_normal_one_pass(self):
        self.plan_with("| 1 | build | `cargo test` | sonnet | high | 1m | 10k | |",
                       "| 2 | install | after the landing: `x` works | sonnet | high | 1m | 10k | done |")
        self.assertEqual(self.rules(), [])

    def test_a_milestone_row_needs_its_reason(self):
        self.plan_with("| 1 | Milestone 1: land the core | `cargo test` | sonnet | high | 1m | 10k | |")
        self.assertEqual(self.rules(), ["plan-milestone-reason"])
        self.plan_with("| 1 | Milestone 1: land the core | needs a new main: the hub needs the core; `cargo test` "
                       "| sonnet | high | 1m | 10k | |")
        self.assertEqual(self.rules(), [])


class HitchedFreezeTest(unittest.TestCase):
    setUp, tearDown = test_plan.PlanTest.setUp, test_plan.PlanTest.tearDown
    run_plan, plan, write_plan = test_plan.PlanTest.run_plan, test_plan.PlanTest.plan, test_plan.PlanTest.write_plan

    def hitch(self):
        self.write_plan()
        self.plan("use", "2")
        runstate.write(self.root, SLUG, "hitched")

    def test_a_hitched_plan_refuses_a_reopened_step_with_the_follow_up_hint(self):
        self.hitch()
        result = self.run_plan("status", "3", "next")
        self.assertEqual(result.returncode, 1)
        self.assertIn("plan.py new --autogenerated", result.stderr)
        self.assertEqual(runstate.read(self.root)["state"], "hitched")
        self.assertEqual(self.run_plan("status", "3", "done").returncode, 0)  # a done mark is no reopening

    def test_a_hitched_plan_refuses_step_add(self):
        self.plan("new", "Two", "--schema", "2")
        runstate.write(self.root, self.plan("current")["slug"], "hitched")
        result = self.run_plan("step", "add", "1", "more")
        self.assertEqual(result.returncode, 1)
        self.assertIn("follow-up", result.stderr)

    def test_other_states_and_other_plans_are_not_frozen(self):
        self.hitch()
        self.write_plan("0003-other", test_plan.EXISTING)
        self.assertEqual(self.run_plan("status", "2", "next", "--plan", "3").returncode, 0)
        runstate.write(self.root, SLUG, "working")
        self.assertEqual(self.run_plan("status", "3", "next").returncode, 0)

    def test_guard_unit(self):
        self.hitch()
        with self.assertRaises(plan_rules.Frozen):
            plan_rules.guard(self.root, "status", SLUG, "next")
        plan_rules.guard(self.root, "status", SLUG, "done")
        plan_rules.guard(self.root, "check", SLUG)


if __name__ == "__main__":
    unittest.main()
