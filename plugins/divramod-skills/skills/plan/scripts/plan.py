def dispatch(root: Path, args) -> int:
    """A repository's command on `root`'s plans (the files, or the store home's view: storerun.py)."""
    try:
        if args.command == "check":
            return run_check(root, args.folders, args.json)
        if args.command == "convert":
            return convert.run(root, args, plan_files, resolve)
        if args.command in shape_cmds.ROUTED:
            path = resolve(root, args.plan) if getattr(args, "plan", None) else current_path(root)
            if shape_cmds.routed(path, args.command):
                out, code = shape_cmds.run(root, path, args,
                                           lambda p: {**describe(root, p), **spec_link.fields(root, p)})
                sys.stdout.write(out if isinstance(out, str) else json.dumps(out, indent=2, ensure_ascii=False) + "\n")
                return code
        if args.command in ("masterplan", *masterplan.NO_STEPS):
            path = resolve(root, args.plan) if args.plan else current_path(root)
            if args.command == "masterplan":
                return masterplan_view.show(root, path, args.json, lambda p: describe_safe(root, p)["steps"])
            masterplan.refuse_step(path, args.command, getattr(args, "step", ""))
        if args.command == "trailers":
            path = resolve(root, args.plan) if args.plan else current_path(root)
            if not args.step:
                raise PlanError("trailers needs the step's number")
            found = trailers.lines(root, slug_of(path), [s["number"] for s in read_steps(path.read_text())], args.step)
            if not neutral_commit.trailers(root, found):
                print("\n".join(found))
            return 0
        if args.command == "scope":
            path = resolve(root, args.plan) if args.plan else current_path(root)
            text = path.read_text()
            head = trailers.scope(slug_of(path), masterplan.parent_of(text), [s["number"] for s in read_steps(text)],
                                  args.step)
            if not neutral_commit.scope(root):
                print(head)
            return 0
        if args.command == "new":
            spec_info, into, designs = spec_link_args(root, args)
            if (added := stays.guard_new(root, args)) is not None:
                print(json.dumps(added, indent=2, ensure_ascii=False))
                return 0
            if args.here and not args.no_current:
                stays.switch(root, "(new)")
            master = masterplan.check_new(args.masterplan, args.research,
                                          resolve(root, args.parent) if args.parent else None)
            sown = seed.read(root, args.seed) if args.seed else None
            path = new_plan(root, args.title, args.goal, not args.no_current, args.fetch, args.research,
                            "manual" if args.manual_landing or args.research or args.masterplan else "auto",
                            args.autogenerated, args.parallel, seed.context_line(sown) if sown else "",
                            args.masterplan, into, args.schema)
            if spec_info:
                spec_link.seed(path, spec_info, designs)
            if master:
                masterplan.adopt(master, path, names.default_ref(root))
                stamp_finished(master)
            result = describe(root, path)
            if spec_info:
                result.update(spec_link.fields(root, path))
            if sown:
                result["seed"] = seed.mark(root, sown)
        elif args.command == "current":
            path = current_path(root)
            result = {**describe(root, path), **spec_link.fields(root, path)}
        elif args.command == "list":
            result = [describe_safe(root, p) for p in plan_files(root)]
        elif args.command == "leave":
            result = masterplan_keep.leave(root, lambda p: read_steps(p.read_text()), args.release)
        elif args.command == "use":
            path = resolve(root, args.plan)
            stays.guard_use(root, slug_of(path), args.here)
            set_current(root, path)
            result = describe(root, path)
        elif args.command == "run":
            result = run_values(resolve(root, args.plan) if args.plan else current_path(root), args)
        elif args.command == "migrate":
            result = migrate(root, resolve(root, args.plan) if args.plan else current_path(root))
        elif args.command == "prompt":
            result = prompt_call(root, resolve(root, args.plan) if args.plan else current_path(root), args)
        elif args.command in shape_cli.COMMANDS:
            out, code = shape_cli.run(root, resolve(root, args.plan) if args.plan else current_path(root), args)
            if isinstance(out, str):
                sys.stdout.write(out)
            else:
                print(json.dumps(out, indent=2, ensure_ascii=False))
            return code
        elif args.command in PARALLEL_COMMANDS:
            path = resolve(root, args.plan) if args.plan else current_path(root)
            return run_parallel(root, path, args)
        else:
            path = resolve(root, args.plan) if args.plan else current_path(root)
            written = note = ticked = None
            if args.command == "status":
                ticked = set_status(path, args.step, args.status)
                if args.status.strip().lower() == "next":
                    written = scaffold_step(path, args.step)
            elif args.command == "landing":
                set_landing(path, args.landing)
            elif args.command == "uat":
                write_uat(path, args.shotfile)
            elif args.command == "changelog":
                _, note = changelog.write(root, path.parent, is_research(slug_of(path)))
            elif args.command == "scaffold":
                folder.scaffold_existing(root, path)
            else:
                set_grilled(path, args.auto)
            result = describe(root, path)
            if note:
                result["changelog_next"] = note
            if written:
                result["step_file"] = rel(written, root)
            result.update(masterplan_keep.report(ticked))
    except ERRORS as error:
        print(f"plan.py: {error}", file=sys.stderr)
        return 1
    print(json.dumps(result, indent=2, ensure_ascii=False))
    return 0


def spec_link_args(root: Path, args) -> tuple[dict | None, Path | None, list[dict]]:
    """`new --spec`: the spec, its folder and its accepted designs; fills the title and goal from the spec. Without
    `--spec` a CURRENT_PLAN that names a spec with no plan yet is an error (the hint), unless `--no-spec`."""
    if not args.spec:
        if not args.title:
            raise PlanError("new needs a title (or --spec <n>)")
        if not args.no_spec and (hint := spec_link.hint(root)):
            raise PlanError(hint)
        return None, None, []
    if args.research or args.masterplan or args.parent or args.seed:
        raise PlanError("--spec cannot be combined with --research, --masterplan, --parent or --seed")
    info, folder = spec_link.load(root, args.spec)
    args.title = args.title or info["title"]
    args.goal = args.goal or info["description"]
    for line in spec_link.warnings(info):
        print(f"plan.py: warning: {line}", file=sys.stderr)
    return info, folder, spec_link.accepted(root, folder)


def run_values(path: Path, args) -> dict:
    """`plan.py run`: --check compares `run` with the session's live values, --sync writes them into it, --model,
    --effort and --window set those words (the others kept); a legacy plan's line is `Run:`."""
    before = header_value(path.read_text(), "Run")
    live = session.live()
    explicit = {k: v for k, v in (("model", args.model), ("effort", args.effort), ("window", args.window)) if v}
    if args.check and explicit:
        raise PlanError("run --check compares only: set values without it")
    if args.sync and explicit:
        raise PlanError("run --sync takes the live values: name values without it")
    if not (args.check or args.sync or explicit):
        raise PlanError("run needs --sync, --check or --model/--effort/--window")
    if args.model and not sizing.RUN_MODEL.match(session.model_id(args.model)):
        raise PlanError(f"--model '{args.model}' is none of {', '.join(sizing.MODELS)} nor a full id")
    words = (list(run_default(path.read_text())) + ["", "", ""])[:3]
    if args.sync:
        words = sizing.run_words(live, or_template(words))
    elif explicit:
        for k, name in enumerate(("model", "effort", "window")):
            if name in explicit:
                words[k] = session.model_id(explicit[name]) if name == "model" else explicit[name]
    run = " ".join(w or "-" for w in words).strip()
    if not args.check and run != before:
        set_header(path, "Run", run)
    after = header_value(path.read_text(), "Run")
    return {"plan": slug_of(path), "run": after, "before": before, "live": live, "drift": context.drift(live, after)}


def prompt_call(root: Path, path: Path, args) -> dict:
    """`plan.py prompt`: the Agent call of one step (prompt.py); the other open steps are named as off limits."""
    text = path.read_text()
    steps = read_steps(text)
    row = next((s for s in steps if s["number"] == args.step), None)
    if row is None:
        raise PlanError(f"no step '{args.step}' in {slug_of(path)}")
    if path.name != MAIN:
        raise PlanError("a flat plan file has no folder for steps/<n>.md: move it into plans/<NNNN>-<slug>/")
    if args.part is not None and args.part < 2:
        raise PlanError("--part counts the retries from 2 (part 1 is the first run)")
    others = [s for s in steps if s["number"] != row["number"] and not s["status"].lower().startswith("done")]
    columns = steps_table(text.splitlines())[1] if folder.is_record(text) else None
    return step_prompt.call(root, path, row, others, columns, args.part, args.model, args.effort)


def migrate(root: Path, path: Path) -> dict:
    """`plan.py migrate`: a record plan's step table gets the columns Model, Effort, Window and Size where missing,
    its open rows the values (sizing.migrate_row), its `run` the session's live values. A legacy plan is never
    touched."""
    text = path.read_text()
    if not folder.is_record(text):
        return {"plan": slug_of(path), "migrated": False, "why": "a legacy plan: never migrated"}
    old_run = list(run_default(text))
    lines = text.splitlines(keepends=True)
    header, cols, rows = table_rows([l.rstrip("\n") for l in lines])
    width = table.width(lines, header)
    new_header = sizing.migrate_header(split_row(lines[header]))
    new_cols = {name.lower(): i for i, name in enumerate(new_header)}
    lines[header] = join_row(new_header) + "\n"
    lines[header + 1] = join_row(sizing.migrate_row(split_row(lines[header + 1]), cols, new_cols, old_run, True)) + "\n"
    for i, cells in rows:
        if misfit := table.misfit(cells, width):
            raise PlanError(f"{slug_of(path)} is not migrated: the row of step {cells[cols['#']]} {misfit}")
        lines[i] = join_row(sizing.migrate_row(cells, cols, new_cols, old_run, False)) + "\n"
    path.write_text("".join(lines))
    set_header(path, "Run", " ".join(sizing.run_words(session.live(), or_template(old_run))))
    result = describe(root, path)
    result["migrated"] = True
    return result


def run_check(root: Path, folders: list[Path], as_json: bool = False) -> int:
    """The plan-folder check: the plan numbers, then hal2's records checker (checker.py) over the plan folders, or
    over the named ones only, then the sizing of the open steps of every record plan (`plan-steps-sized`,
    sizing.py) and a schema 2 plan's shape rules (shape_check.py). A plan.md without front matter is legacy and
    passes; without the checker the records are unchecked (one line, no failure), the sizing still is. A named spec
    folder (spec.md, no plan.md yet: the spec skill, hal2 plan 0364 D8) has only its records checked."""
    code = 0
    if folders:
        missing = [str(f) for f in folders if not (f / MAIN).is_file() and not (f / "spec.md").is_file()]
        if missing:
            raise PlanError(f"no plan folder (a folder holding {MAIN} or spec.md): {', '.join(missing)}")
    elif planhome.view_of(root) is None:  # the store numbers its plans: no clash to find
        with contextlib.redirect_stdout(sys.stderr if as_json else sys.stdout):
            code = plan_number.main(["--root", str(root), "check"])
    plans = [f.resolve() / MAIN for f in folders if (f / MAIN).is_file()] if folders else plan_files(root)
    local, advisory = local_problems(root, plans)
    try:
        found, skipped = records_found(root, folders, plans)
    except checker.CheckerError as error:
        print(error, file=sys.stderr)
        return error.code
    notes = [n for n in ([checker.NOT_INSTALLED] if found is None else []) + [advisory, skipped] if n]
    problems = (found[1] if found else []) + local
    if as_json:
        print(json.dumps({"problems": problems, "records": found[0] if found else None, "records_skipped": skipped,
                          "notes": notes}, indent=2, ensure_ascii=False))
    else:
        print("\n".join(notes + (problems or ([f"ok: {found[0]} records"] if found is not None else []))))
    return 1 if problems else code


def local_problems(root: Path, plans: list[Path]) -> tuple[list[str], str | None]:
    """The skill's own problems of `plans`: sizing (schema 1 by the step table, schema 2 by shape_check), Brief,
    names, the questions' Q form; and the questions' advisory line."""
    rel = lambda p: in_root(p, root)  # noqa: E731
    shaped = {p for p in plans if p.name == MAIN and shape.is_shape(p.parent)}
    out = [line for p in plans if p not in shaped for line in steps_problems(p.read_text(), rel(p))]
    out += [line for p in plans for line in brief_problems(p.read_text(), rel(p))]
    out += names.problems(root, plans, current_name(root), slug_of)
    marker = parallel.subservant_marker(root, Path.cwd())
    lead = marker["plan"] if marker and shape_lead.subplan_of(marker) else None
    out += [line for p in sorted(shaped) for line in shape_check.problems(root, p.parent, p.parent.name == lead)]
    asked, advisory = question_problems(root, plans)
    return out + asked, advisory


def records_found(root: Path, folders: list[Path], plans: list[Path]):
    """check_records' (count, problems), or None without the checker; and why its findings on schema 2 plans are
    dropped (shape_check.records_skip: a checker older than 0.7.0 runs its schema 1 spec on them)."""
    shaped = [p.parent for p in plans if p.name == MAIN and shape.is_shape(p.parent)]
    skipped = shape_check.records_skip(shaped)
    if skipped and folders and {f.resolve() for f in folders} <= {s.resolve() for s in shaped}:
        return (0, []), skipped
    try:
        found = storerun.records(root, folders) if planhome.view_of(root) else \
            check_records(root, [f.resolve() for f in folders])
    except checker.CheckerError as error:
        if not skipped:
            raise
        return (0, []), f"{skipped}; the other plans unchecked too ({error})"
    if found and skipped:
        prefixes = tuple(f"{in_root(s, root)}/" for s in shaped)
        found = (found[0], [line for line in found[1] if not line.startswith(prefixes)])
    return found, skipped


def question_problems(root: Path, plans: list[Path]) -> tuple[list[str], str | None]:
    """The Q-form problems of the questions.md of every record plan checked (qcheck.py, rule `questions-q-form`):
    an open question of the agent needs exactly three option lines; the advisory line when hal2-cli-plans is not
    there. A legacy plan (no front matter) and a plan without a questions.md pass."""
    stores = [(in_root(p.parent / "questions.md", root), p.parent / "questions.md")
              for p in plans if p.name == MAIN and (p.parent / "questions.md").is_file()
              and folder.is_record(p.read_text())]
    return qcheck.check(stores) if stores else ([], None)


def check_records(root: Path, folders: list[Path]) -> tuple[int, list[str]] | None:
    """The checker's records and problems of the plans folder, or of the named plan folders: a folder of this
    repository is checked with the repository (its .hal/records.toml applies), any other (an example folder laid
    out like a repository, `<tree>/plans/<plan>/`) with `--folder <tree>`. None without the checker."""
    real = root.resolve()
    if not folders:
        result = checker.check(repo=real)
        if result is None:
            return None
        return result["records"], [checker.line(p) for p in result["problems"] if p["path"].startswith(f"{PLANS}/")]
    count, problems, runs = 0, [], {}
    for path in folders:
        runs.setdefault(path.parent.parent, []).append(path.name)
    for tree, names in runs.items():
        result = checker.check(repo=real) if tree == real else checker.check(folder=tree)
        if result is None:
            return None
        count += result["records"]
        prefix = "" if tree == real else f"{os.path.relpath(tree, real)}/"
        problems += [checker.line(p, prefix) for p in result["problems"]
                     if any(p["path"].startswith(f"{PLANS}/{name}/") for name in names)]
    return count, problems


