def use_global(folder: Path) -> Path:
    """Work on the global plans folder `folder`: plans are `folder/<slug>/plan.md`; the root to pass on."""
    global PLANS, GLOBAL
    PLANS = Path(folder.name)
    GLOBAL = True
    return folder.parent


def global_folder() -> Path:
    """hal2's global plans folder (`hal2-cli-plans settings --json`)."""
    if shutil.which("hal2-cli-plans") is None:
        raise PlanError("hal2-cli-plans is missing: install hal2 (cargo install --path apps/hal2-cli-plans)")
    out = subprocess.run(["hal2-cli-plans", "settings", "--json"], capture_output=True, text=True)
    if out.returncode != 0:
        raise PlanError(f"hal2-cli-plans settings: {out.stderr.strip()}")
    return Path(json.loads(out.stdout)["root"])


def new_global_plan(folder: Path, title: str, goal: str, research: bool) -> Path:
    """A global plan, numbered and written by hal2 (`hal2-cli-plans new --global`)."""
    names.refuse(title)
    if shutil.which("hal2-cli-plans") is None:
        raise PlanError("hal2-cli-plans is missing: install hal2 (cargo install --path apps/hal2-cli-plans)")
    args = ["hal2-cli-plans", "new", title, "--global", "--json"]
    if goal:
        args += ["--goal", goal]
    if research:
        args.append("--research")
    out = subprocess.run(args, capture_output=True, text=True)
    if out.returncode != 0:
        raise PlanError(f"hal2-cli-plans new: {out.stderr.strip()}")
    path = Path(json.loads(out.stdout)["path"]).resolve()
    if path.parent.parent.resolve() != folder.resolve():
        raise PlanError(f"hal2-cli-plans created {path}, outside the global folder {folder}")
    return path


def plans_dir(root: Path) -> Path:
    """The folder of the plan folders: the global folder, a store-home checkout's view (planhome.py), else
    `<root>/plans`."""
    return root / PLANS if GLOBAL else planhome.plans_dir(root)


def rel(path: Path, root: Path) -> str:
    """`path` below `root` as the checkout names it (`plans/<...>` also for a file of the store home's view)."""
    return str(path.relative_to(root)) if GLOBAL else planhome.rel(path, root)


def in_root(path: Path, root: Path) -> str:
    """`path` relative to `root` by its real location (`os.path.relpath`), a file of the store home's view as
    `plans/<...>`."""
    if planhome.view_of(root) is not None and not GLOBAL:
        return planhome.rel(path, root)
    return os.path.relpath(path.resolve(), root.resolve())


def find_root(start: Path) -> Path:
    for folder in [start, *start.parents]:
        if (folder / ".git").exists():
            return folder
    raise PlanError(f"not inside a git repository: {start}")


def slugify(title: str) -> str:
    slug = re.sub(r"[^a-z0-9]+", "-", title.lower()).strip("-")
    if not slug:
        raise PlanError("title needs at least one letter or digit")
    return slug[:60].rstrip("-")


def research_slug(slug: str) -> str:
    """`research-<slug>` for a research plan, unless the slug already starts with it."""
    if slug == RESEARCH or slug.startswith(RESEARCH + "-"):
        return slug
    return f"{RESEARCH}-{slug}"[:60].rstrip("-")


def is_research(slug: str) -> bool:
    """A research plan: `<NNNN>-research-<topic>`."""
    name = slug[5:]
    return name == RESEARCH or name.startswith(RESEARCH + "-")


def slug_of(path: Path) -> str:
    """`0002-foo` for plans/0002-foo/plan.md (and for a flat plans/0002-foo.md)."""
    return path.parent.name if path.name == MAIN else path.stem


def plan_files(root: Path) -> list[Path]:
    """Every plan's markdown file: plans/<slug>/plan.md, or a flat plans/<slug>.md."""
    folder = plans_dir(root)
    if not folder.is_dir():
        return []
    found = [p / MAIN for p in folder.iterdir() if p.is_dir() and PLAN_RE.match(p.name) and (p / MAIN).is_file()]
    found += [p for p in folder.iterdir() if p.is_file() and p.suffix == ".md" and PLAN_RE.match(p.stem)]
    return sorted(found, key=slug_of)


def resolve(root: Path, ref: str) -> Path:
    """A plan by slug (`0002-foo`), file name, or bare number (`2`, `0002`)."""
    ref = ref.strip().removesuffix(".md").removesuffix("/" + MAIN).rstrip("/")
    for path in plan_files(root):
        slug = slug_of(path)
        if slug == ref or (ref.isdigit() and int(ref) == int(slug[:4])):
            return path
    raise PlanError(f"no plan matches '{ref}' in {PLANS}")


def current_name(root: Path) -> str:
    """What the checkout's CURRENT_PLAN names (the git dir's, else plans/), "" for none; a global folder has none."""
    return "" if GLOBAL else pointers.read(root, POINTER)


def current_path(root: Path) -> Path:
    ref = current_name(root)
    if not ref:
        raise PlanError(f"no current plan: {PLANS / POINTER} is missing or empty")
    try:
        return resolve(root, ref)
    except PlanError:
        # A shot (`<shotfile>/<n>`) or a task name: current work, but no plan.
        raise PlanError(f"no current plan: {PLANS / POINTER} names '{ref}', which is not a plan") from None


def set_current(root: Path, path: Path) -> None:
    pointers.write(root, POINTER, slug_of(path))  # the git dir in the store home, else plans/


def steps_table(lines: list[str]) -> tuple[int, dict[str, int]]:
    """Index of the step table's header line and its column positions (table.py)."""
    found = table.header(lines)
    if found is None:
        raise PlanError("no step table with columns '#', 'Step' and 'Status'")
    return found


def run_default(text: str) -> tuple[str, str, str]:
    """The plan's `run` as model, effort and window: a record's `run` key (the coordinator's), a legacy plan's
    `Run: <model> <effort>` line (`-` for none); empty strings for what it does not name."""
    words = [w.strip("`") for w in header_value(text, "Run").split()] + ["", "", ""]
    return tuple("" if w == "-" else w for w in words[:3])


def template_run() -> list[str]:
    """The template's `run` words: what `new`, `run --sync` and `migrate` write for a value the session does not
    name."""
    found = re.search(r"^run: (.+)$", TEMPLATE.read_text(), re.M)
    return (found.group(1).split() if found else []) + [""] * 3


def or_template(words) -> list[str]:
    return [w or t for w, t in zip(list(words) + ["", "", ""], template_run())][:3]


def table_rows(lines: list[str]) -> tuple[int, dict[str, int], list[tuple[int, list[str]]]]:
    """The step table's header line, its column positions and its rows as (line index, cells)."""
    header, cols = steps_table(lines)
    rows, width = [], max(cols.values()) + 1
    for row, (i, cells) in enumerate(table.rows(lines, header), 1):
        if len(cells) < width:
            raise PlanError(f"row {row} of the step table has {len(cells)} cells, its header {width}: write a `|` "
                            "inside a cell as `\\|`")
        rows.append((i, cells))
    return header, cols, rows


def read_steps(text: str) -> list[dict]:
    """The step rows. A record plan's rows name their own Model, Effort and Window (`run` is the coordinator's); a
    legacy plan's empty cells take its `Run:` line."""
    lines = text.splitlines()
    run = ("", "", "") if folder.is_record(text) else run_default(text)
    try:
        header, cols, rows = table_rows(lines)
    except PlanError as error:
        if str(error).startswith("no step table"):
            return []
        raise
    steps = []
    for _, cells in rows:
        cell = lambda name: cells[cols[name]] if name in cols else ""
        step = {
            "number": cells[cols["#"]],
            "step": cells[cols["step"]],
            "done_when": cell("done when"),
            "status": cells[cols["status"]],
            "model": cell("model") or run[0],
            "effort": cell("effort") or run[1],
            "window": cell("window") or run[2],
            "size": cell("size"),
        }
        if parallel.is_parallel(cols):
            parallel.enrich(step, cells, cols)
        steps.append(step)
    for step in steps:
        step["after_landing"] = step["done_when"].lower().lstrip("*_ ").startswith(AFTER_LANDING)
    return steps


def header_value(text: str, key: str) -> str:
    """The value of a `<key>: <value>` line above the plan's first section; of a plan in the record format, its
    front matter key."""
    if folder.is_record(text):
        return folder.header(text, key)
    for line in text.splitlines():
        if line.startswith("## "):
            break
        if line.startswith(key + ":"):
            return line.split(":", 1)[1].strip()
    return ""


def landing_of(text: str) -> str:
    """auto, manual (also for a plan without the line or with an unknown value) or none (a global plan)."""
    if GLOBAL:
        return "none"
    value = header_value(text, "Landing").lower()
    return value if value in LANDINGS else "manual"


def problems_of(steps: list[dict]) -> list[str]:
    """After-landing steps that other steps follow: they belong at the end of the table."""
    problems = []
    for i, step in enumerate(steps):
        later = [s["number"] for s in steps[i + 1:] if not s["after_landing"]]
        if step["after_landing"] and later:
            problems.append(f"step {step['number']} is checked after the landing but step(s) {', '.join(later)} "
                            "follow it: move it to the end, a plan lands once, after all its other steps")
    return problems


def run_line(lines: list[str]) -> int | None:
    """The index of the front matter's `run:` line, or None."""
    if not lines or lines[0] != "---":
        return None
    for i, line in enumerate(lines[1:], 1):
        if line == "---":
            return None
        if line.startswith("run:"):
            return i
    return None


def steps_problems(text: str, label: str) -> list[str]:
    """The `plan-steps-sized` lines of a record plan with an open row (sizing.py); a legacy plan has none."""
    if not folder.is_record(text) or masterplan.of_text(Path(label).parent.name, text):
        return []  # a legacy plan; a masterplan, whose rows are plans and are not sized
    lines = text.splitlines()
    try:
        header, cols, rows = table_rows(lines)
    except PlanError:
        return []
    return sizing.problems(label, header_value(text, "Run"), run_line(lines), header, cols, rows)


def describe(root: Path, path: Path) -> dict:
    text = path.read_text()
    steps = read_steps(text)
    title = next((l[2:].strip() for l in text.splitlines() if l.startswith("# ")), slug_of(path))
    grilled = header_value(text, "Grilled")
    open_steps = [s for s in steps if not s["status"].lower().startswith("done")]
    before_landing = [s for s in open_steps if not s["after_landing"]]
    landing = landing_of(text)
    land = landing if landing != "auto" else ("wait" if before_landing else "ready")
    extra = {}
    if steps and "needs" in steps[0]:
        ready, _ = parallel.schedule(steps, parallel.capacity(text))
        extra = {"parallel": True, "running": [s for s in steps if parallel.kind(s["status"]) == "running"],
                 "ready": ready}
    if not GLOBAL and (marker := parallel.read_marker(root)):
        extra["lead"] = marker
    return {
        "slug": slug_of(path),
        "path": rel(path, root),
        "title": title,
        "research": is_research(slug_of(path)),
        **masterplan.fields(path, text),
        "current": current_name(root) == slug_of(path),
        "grilled": grilled,
        "finished": header_value(text, "Finished"),
        "uat": rel(path.parent / UAT, root) if (path.parent / UAT).exists() and path.name == MAIN else "",
        "uat_checks": uat_checks(path),
        "changelog": rel(path.parent / changelog.FILE, root)
                     if path.name == MAIN and (path.parent / changelog.FILE).exists() else "",
        "brief": brief.filled(text),
        "autogrill_rounds": grill_rounds(grilled)[0],
        "autogenerated": header_value(text, "Autogenerated"),
        "format": "record" if folder.is_record(text) else "legacy",
        **{name[:-3]: rel(path.parent / name, root) if path.name == MAIN and (path.parent / name).is_file()
           else "" for name in folder.SIBLINGS},
        "done": len(steps) - len(open_steps),
        "total": len(steps),
        "next": (before_landing or open_steps or [None])[0],
        "landing": landing,
        "land": land,
        "problems": problems_of(steps) + (parallel.problems(steps) if extra.get("parallel") else [])
                    + steps_problems(text, rel(path, root)),
        "steps": steps,
        **extra,
    }


def brief_problems(text: str, label: str) -> list[str]:
    """The `plan-brief-filled` lines (brief.py) of a plan that is not done: finished, or every step done, passes."""
    return brief.problems(text, label, bool(header_value(text, "Finished")))


def describe_safe(root: Path, path: Path) -> dict:
    """describe(), or the plan's error as its only problem: one broken table never hides the other plans."""
    try:
        return describe(root, path)
    except PlanError as error:
        return {"slug": slug_of(path), "path": rel(path, root), "problems": [str(error)], "steps": []}


def parallel_table(text: str) -> str:
    """The template's step table with the parallel plan's columns Needs, Touches and Who (the UAT step needs every
    step before it)."""
    lines, out, ids, header = text.split("\n"), [], [], None
    for line in lines:
        if not line.lstrip().startswith("|"):
            out.append(line)
            continue
        cells = split_row(line)
        if header is None:
            header = cells
            cells[2:2] = ["Needs", "Touches", "Who"]
        elif set("".join(cells)) <= set("-: "):
            cells[2:2] = ["---"] * 3
        else:
            uat = "Write the UATs" in cells[1]
            cells[2:2] = [", ".join(ids) if uat else "", "docs" if uat else "", "lead" if uat else ""]
            ids.append(cells[0])
        out.append(join_row(cells))
    return "\n".join(out)


def new_plan(root: Path, title: str, goal: str, make_current: bool, fetch: bool = False,
             research: bool = False, landing: str = "auto", autogenerated: str = "", parallel_plan: bool = False,
             seed_line: str = "", master: bool = False, into: Path | None = None, schema: int = 1) -> Path:
    """`into`: the spec folder the plan is written into (its number and slug stay), else a new numbered folder.
    `schema` 2 writes the one plan shape (shape_new.py: plan.md's overview, `subplans/01-<slug>`, `99-uat`); a
    masterplan and a parallel plan stay schema 1 (`schema` 1 writes the old step table)."""
    names.refuse(title)
    slug = research_slug(slugify(title)) if research else slugify(title)
    slug = masterplan.marked(slug) if master else slug
    if into is None and planhome.view_of(root) is not None and not GLOBAL:
        into = storerun.claim(root, slug)  # the store numbers the plan; plan.py's own template fills it
    if into is not None:
        number = int(into.name[:4])
    else:
        if fetch:
            plan_number.git(root, "fetch", "--all", "--quiet")
        try:
            number = plan_number.next_number(root, slug)
        except plan_number.NumberError as error:
            raise PlanError(str(error)) from error
    path = (into or plans_dir(root) / f"{number:04d}-{slug}") / MAIN
    path.parent.mkdir(parents=True, exist_ok=True)
    values = folder.fields(root, number, title, goal, landing)
    subplans = schema == 2 and not master and not parallel_plan
    text = masterplan.template(root, values) if master else \
        (TEMPLATE_SHAPE if subplans else TEMPLATE).read_text().format(**values)
    if research:
        text = "\n".join(l for l in text.split("\n") if "Write the UATs" not in l)
    text = text.replace("- Seed: <seedbag>#<n>", seed_line) if seed_line else text.replace("- Seed: <seedbag>#<n>\n", "")
    if parallel_plan and not master:
        text = parallel_table(text)
    path.write_text(text)
    set_header(path, "Run", " ".join(sizing.run_words(session.live(), template_run())))
    if subplans:
        shape_new.scaffold(root, path.parent, title, goal, research)
    folder.scaffold(path, values)
    if autogenerated:
        set_header(path, "Autogenerated", f"{autogenerated}, {dt.date.today().isoformat()}")
    if make_current:
        set_current(root, path)
    return path


def set_status(path: Path, step: str, status: str) -> dict | None:
    return set_cells(path, step, {"status": status})


def size_line(row: dict) -> str:
    """The step file's `Size: <size> of <window>` line (the row's estimated peak context and its window), empty when
    the row names neither (a legacy row)."""
    size, window = (row.get("size") or "").strip(), (row.get("window") or "").strip()
    return f"Size: {size or '?'} of {window or '?'}\n" if size or window else ""


def scaffold_step(path: Path, step: str) -> Path | None:
    """Write `steps/<step>.md` from templates/step.md when the step becomes next (hal2's record
    plans-short-and-concise): never over an existing file, never for a flat plan (no folder) or a masterplan (its
    rows are plans). The written file, or None."""
    target = path.parent / STEPS / f"{step}.md"
    if path.name != MAIN or target.exists() or masterplan.of(path):
        return None
    text = path.read_text()
    row = next((s for s in read_steps(text) if s["number"] == step), None)
    if row is None:
        return None
    target.parent.mkdir(exist_ok=True)
    target.write_text(STEP_TEMPLATE.read_text().format(
        number=step, title=row["step"] or f"step {step}",
        task="<what to change: the files and packages, the approach, what the step must not touch>",
        size_line=size_line(row), done_when=row["done_when"] or "the step table's check"))
    return target


def set_cells(path: Path, step: str, values: dict[str, str]) -> dict | None:
    """Set cells of one step's row by column name (lower case), keeping every other cell. A masterplan's row the
    change ticked or took back (`stamp_finished`), else None."""
    lines = path.read_text().splitlines(keepends=True)
    header, cols = steps_table([l.rstrip("\n") for l in lines])
    missing = [name for name in values if name not in cols]
    if missing:
        raise PlanError(f"the step table of {slug_of(path)} has no column {', '.join(missing)}")
    for i in range(header + 2, len(lines)):
        if not lines[i].lstrip().startswith("|"):
            break
        cells = split_row(lines[i])
        if cells and cells[cols["#"]] == step:
            if misfit := table.misfit(cells, table.width(lines, header)):
                raise PlanError(f"step {step} of {slug_of(path)} is not written: its row {misfit}")
            for name, value in values.items():
                cells[cols[name]] = value
            lines[i] = join_row(cells) + "\n"
            path.write_text("".join(lines))
            return stamp_finished(path)
    raise PlanError(f"no step '{step}' in {slug_of(path)}")


def feature_of(title: str) -> str:
    """The feature a plan's title names first (`plugin-plan 9, 8` → `plugin-plan`): its shotfile's name."""
    return slugify(title.split()[0]) if title.split() else ""


def uat_checks(path: Path) -> list[str]:
    uat = path.parent / UAT
    if path.name != MAIN or not uat.exists():
        return []
    return [m.group(1) for l in uat.read_text().splitlines() if (m := UAT_CHECK.match(l))]


def write_uat(path: Path, shotfile: str = "") -> Path:
    """Scaffold the plan's `uat.md` from the template, typed (`type: UAT`, hal2's spec `uat`; never overwrites one)."""
    if path.name != MAIN:
        raise PlanError("a flat plan file has no folder for its uat.md: move it into plans/<NNNN>-<slug>/")
    uat = path.parent / UAT
    if not uat.exists():
        text = path.read_text()
        title = next((l.split(":", 1)[1].strip() for l in text.splitlines() if l.startswith("# Plan ")), slug_of(path))
        title = " ".join(title.split())
        number = slug_of(path)[:4]
        feature = shotfile.removesuffix(".md") or feature_of(title)
        out = UAT_TEMPLATE.read_text().format(
            number=number, id=int(number), title=title, quoted_title=envelope.quote(title),
            description=envelope.quote(f"The checks a person runs by hand on the default branch after plan {number} landed."),
            date=dt.date.today().isoformat(), shotfile=feature,
        )
        uat.write_text(out if feature else out.replace("shotfile: \n", ""))
    return uat


def stamp_finished(path: Path) -> dict | None:
    """`Finished: <date>` once every step is done (hal2 shows it); gone again when a step reopens. A plan of a
    masterplan then ticks its row there or takes the tick back (masterplan_keep.tick), and the masterplan is stamped
    like every plan; that tick ({masterplan, row, status, masterplan_finished}; `skipped`: why a row was not held),
    else None."""
    text = path.read_text()
    steps = read_steps(text)
    finished = bool(steps) and all(s["status"].lower().startswith("done") for s in steps)
    if finished and not header_value(text, "Finished"):
        set_header(path, "Finished", dt.date.today().isoformat())
    elif not finished and header_value(text, "Finished"):
        remove_header(path, "Finished")
    if folder.is_record(text):
        folder.sync_status(path, finished)
    ticked = masterplan_keep.tick(path)
    if ticked and ticked.get("row"):
        master = path.parent.parent / ticked["masterplan"] / MAIN
        stamp_finished(master)
        ticked["masterplan_finished"] = bool(header_value(master.read_text(), "Finished"))
    return ticked


def remove_header(path: Path, key: str) -> None:
    if folder.is_record(path.read_text()):
        return folder.set_header(path, key, None)
    lines = path.read_text().splitlines(keepends=True)
    for i, line in enumerate(lines):
        if line.startswith("## "):
            return
        if line.startswith(key + ":"):
            del lines[i]
            if i < len(lines) and i > 0 and not lines[i].strip() and not lines[i - 1].strip():
                del lines[i]
            path.write_text("".join(lines))
            return


def set_header(path: Path, key: str, value: str) -> None:
    """Set the plan's `<key>: <value>` line, inserting it below the title when missing; a plan in the record format
    gets the front matter key."""
    if folder.is_record(path.read_text()):
        return folder.set_header(path, key, value)
    lines = path.read_text().splitlines(keepends=True)
    for i, line in enumerate(lines):
        if line.startswith("## "):
            break
        if line.startswith(key + ":"):
            lines[i] = f"{key}: {value}\n"
            path.write_text("".join(lines))
            return
    title = next((i for i, l in enumerate(lines) if l.startswith("# ")), -1)
    lines.insert(title + 1, f"\n{key}: {value}\n")
    path.write_text("".join(lines))


GRILL_NOTE = re.compile(r"\((?:autogrill [×x](\d+))?(?:, )?(grill)?\)")


def grill_rounds(grilled: str) -> tuple[int, bool]:
    """Autogrill rounds and whether the user grilled it, from `Grilled: <date> (autogrill ×2, grill)`; a plain
    date is a grill by the user."""
    if not grilled:
        return 0, False
    note = GRILL_NOTE.search(grilled)
    if not note:
        return 0, True
    return int(note.group(1) or 0), bool(note.group(2))


def set_grilled(path: Path, auto: bool = False) -> None:
    """Stamp today, counting autogrill rounds (`--auto`) next to a grill by the user."""
    rounds, manual = grill_rounds(header_value(path.read_text(), "Grilled"))
    if auto:
        rounds += 1
    else:
        manual = True
    notes = ([f"autogrill ×{rounds}"] if rounds else []) + (["grill"] if manual and rounds else [])
    today = dt.date.today().isoformat()
    set_header(path, "Grilled", f"{today} ({', '.join(notes)})" if notes else today)


def set_landing(path: Path, landing: str) -> None:
    if GLOBAL:
        raise PlanError("a global plan never lands: it belongs to no repository")
    set_header(path, "Landing", landing)


