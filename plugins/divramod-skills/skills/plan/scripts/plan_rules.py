"""plan_rules.py: the planner's own rules in code (hal2 plan 0514 step 8, D9, D10).

    plan-no-after-landing   an open step whose done-when starts "after the landing:" fails `plan.py check`: a plan
                            lands once, so such a check belongs in `uat.md` (the user's, or `Auto: yes`)
    plan-milestone-reason   an open row "Milestone <n>" must say why the plan cannot land once ("needs a new main: ...")
    guard                   a plan whose run state is `hitched` is frozen: no reopened and no new step; the work
                            goes into a follow-up plan (`plan.py new --autogenerated`)

Imports no plan.py (that runs as `__main__`); the row and column shapes are the ones plan.py's `table_rows` returns.
"""
from __future__ import annotations

import re
from pathlib import Path

import runstate

AFTER_LANDING = ("after the landing", "after the user's `/mtm`", "after the user's /mtm")
MILESTONE = re.compile(r"^\W*milestone\s+\d+", re.I)
REASON = "needs a new main:"


class Frozen(Exception):
    """A hitched plan asked for a new or reopened step; the message names the follow-up plan."""


def problems(label: str, cols: dict[str, int], rows: list[tuple[int, list[str]]]) -> list[str]:
    """`<label>:<line>: <message> (<rule>)` for every open row against the two rules."""
    out = []
    for i, cells in rows:
        cell = lambda name: cells[cols[name]] if name in cols else ""
        if cell("status").strip().lower().startswith("done"):
            continue
        at, number = f"{label}:{i + 1}", cell("#")
        if cell("done when").lower().lstrip("*_ ").startswith(AFTER_LANDING):
            out.append(f"{at}: step {number}: an open step is checked after the landing, but a plan lands once: put "
                       "the check into uat.md (the user's, or `Auto: yes` for one a script runs after the barn) "
                       "(plan-no-after-landing)")
        if MILESTONE.match(cell("step")) and REASON not in f"{cell('step')} {cell('done when')}".lower():
            out.append(f"{at}: step {number}: a milestone row says why the plan cannot land once, "
                       f"`{REASON} <what>` (plan-milestone-reason)")
    return out


def guard(root: Path | str, command: str, plan: str, status: str = "", action: str = "") -> None:
    """Raises Frozen when `plan` is hitched and the command reopens a step (`status` other than done) or adds one."""
    adds = command == "step" and action == "add"
    reopens = command == "status" and not status.strip().lower().startswith("done")
    if not (adds or reopens):
        return
    held = runstate.read(root)
    if held is None or held["state"] != "hitched" or held["plan"] != plan:
        return
    raise Frozen(f"plan {plan} is hitched for the tollman and frozen: no new or reopened steps. Start a follow-up "
                 'plan instead: plan.py new --autogenerated "<title>" (D10)')
