"""An old plan's plan.md into the one plan shape's (hal2 plan 0376, design §7): a record plan of schema 1 keeps its
keys, gets `schema: 2` and `schedule: serial`, its `## Steps` becomes the generated `## Overview`; a legacy plan
(no front matter) gets its envelope from its lines (`Landing:`, `Run:`, `Created`, `Grilled:`, `Finished:`,
`Autogenerated:`, the title from its heading, the description from its Goal), keeps Goal, Brief, Context and
Pre-authorized, and every other section goes verbatim into `legacy.md` beside it, linked from the Context. The
ledgers and the handoff a plan lacks are scaffolded (folder.py).
"""
from __future__ import annotations

import datetime as dt
import re
import subprocess
from pathlib import Path

import convert_text as text
import envelope
import folder as plan_folder
import shape_names as sn

TEMPLATE = Path(__file__).resolve().parent.parent / "templates" / "plan-schema-2.md"
LEGACY = "legacy.md"
KEPT = ("Goal", "Brief", "Context", "Pre-authorized")
ORDER = ("Goal", "Brief", "Context", "Overview", "Pre-authorized", "Notes")
LINE_KEYS = ("Landing", "Run", "Grilled", "Finished", "Autogenerated", "Created")
NO_PREAUTH = "- none recorded: the plan is older than the section"
DATE = re.compile(r"\d{4}-\d\d-\d\d")


def overview_text() -> str:
    """The template's `## Overview` text: the paragraph and the empty generated block."""
    _, parts = text.sections(envelope.split(TEMPLATE.read_text())[1])
    return dict(parts)["Overview"]


def split_plan(body: str) -> tuple[str, str, list[tuple[str, str]]]:
    """(the H1 line, the text between it and the first section, the sections)."""
    head, parts = text.sections(body)
    lines = head.splitlines(keepends=True)
    at = next((i for i, l in enumerate(lines) if l.startswith("# ")), None)
    if at is None:
        return "", head, parts
    return lines[at].rstrip("\n"), "".join(lines[:at] + lines[at + 1:]), parts


def git_date(root: Path, path: Path, first: bool) -> str:
    try:
        out = subprocess.run(["git", "log", "--format=%as", "--", str(path)], cwd=root, capture_output=True,
                             text=True).stdout.split()
    except OSError:
        return ""
    return (out[-1] if first else out[0]) if out else ""


def line_keys(head: str) -> tuple[dict[str, str], str]:
    """A legacy plan's `<Key>: <value>` lines and `Created <date>.` paragraph; the prose left."""
    keys, kept = {}, []
    for para in re.split(r"\n\s*\n", head):
        lines = []
        for line in para.splitlines():
            found = re.match(rf"^({'|'.join(LINE_KEYS)}):\s*(.*)$", line)
            if found and found.group(1) not in keys:
                keys[found.group(1)] = found.group(2).strip()
            else:
                lines.append(line)
        created = re.match(r"^Created (\d{4}-\d\d-\d\d)\.", "\n".join(lines))
        if created:
            keys.setdefault("Created", created.group(1))
            lines = []  # the old template's sentence about CURRENT_PLAN goes with it
        if any(l.strip() for l in lines):
            kept.append("\n".join(lines))
    return keys, "\n\n".join(kept).strip()


def run_of(value: str) -> str | None:
    words = [w.strip("`") for w in value.split()]
    words = [w for w in words if w and w != "-"]
    if not words:
        return None
    return " ".join((words + ["", "", ""])[:2] + [words[2] if len(words) > 2 else "1m"]).replace("  ", " ")


def legacy_front(root: Path, folder: Path, title: str, goal: str, keys: dict[str, str]) -> str:
    landing = keys.get("Landing", "").lower()
    created = DATE.search(keys.get("Created", "")) or DATE.search(git_date(root, folder / "plan.md", True))
    pairs = [("type", "Plan"), ("schema", "2"), ("id", str(int(folder.name[:4]))),
             ("title", envelope.quote(text.one_line(title))),
             ("description", envelope.quote(text.cut(plan_folder.describe(goal, title)))), ("status", "open"),
             ("landing", landing if landing in ("auto", "manual") else "manual")]
    if run := run_of(keys.get("Run", "")):
        pairs.append(("run", plan_folder.raw(run)))
    pairs.append(("created", created.group(0) if created else dt.date.today().isoformat()))
    for key in ("Grilled", "Finished", "Autogenerated"):
        value = keys.get(key, "")
        if key == "Finished":
            value = (DATE.search(value) or [""])[0] if value else ""
        if value:
            pairs.append((key.lower(), plan_folder.raw(text.one_line(value))))
    pairs.append(("schedule", "serial"))
    return "---\n" + "".join(f"{k}: {v}\n" for k, v in pairs) + "---\n"


def heading(number: int, h1: str, title: str) -> str:
    found = re.match(r"^# Plan \d+:\s*(.*)$", h1)
    return f"# Plan {number:04d}: {found.group(1).strip() if found else title}"


def ordered(parts: dict[str, str]) -> list[tuple[str, str]]:
    return [(name, parts[name]) for name in ORDER if name in parts]


def from_legacy(root: Path, folder: Path, plan_text: str) -> dict:
    """plan.md and legacy.md of a legacy plan; returns {text, legacy, title, goal, finished, landing}."""
    h1, head, parts = split_plan(plan_text)
    keys, prose = line_keys(head)
    title = re.sub(r"^# (Plan \d+:\s*)?", "", h1).strip() or folder.name[5:].replace("-", " ")
    found = dict(parts)
    goal = text.strip_blank(found.get("Goal", "")) or title
    moved = [(t, p) for t, p in parts if t not in KEPT and t != "Steps"]
    legacy = ""
    if moved or prose:
        legacy = (f"# Plan {folder.name[:4]}: {title}, the sections before the one plan shape\n\n"
                  "What plan.md held before its conversion (hal2 plan 0376) that the Plan kind has no section for, "
                  "verbatim.\n" + (f"\n{prose}\n" if prose else "") + text.join_sections(moved))
    context = text.strip_blank(found.get("Context", ""))
    if legacy:
        context += ("\n" if context else "") + f"- The sections from before the one plan shape: [{LEGACY}]({LEGACY})."
    body = {"Goal": goal, "Brief": found.get("Brief"), "Context": context, "Overview": overview_text(),
            "Pre-authorized": found.get("Pre-authorized") or NO_PREAUTH}
    body = {k: v for k, v in body.items() if v is not None}
    out = (legacy_front(root, folder, title, goal, keys) + "\n" + heading(int(folder.name[:4]), h1, title) + "\n"
           + text.join_sections(ordered(body)))
    return {"text": out, "legacy": legacy, "title": title, "goal": goal,
            "finished": (DATE.search(keys.get("Finished", "")) or [None])[0],
            "landing": envelope.get(out, "landing")}


def from_record(plan_text: str) -> dict:
    """plan.md of a record plan of schema 1; returns {text, title, goal, finished, landing}."""
    front, body = envelope.split(plan_text)
    out = envelope.set_key("---\n" + front + "---\n", "schema", "2")
    status = str(envelope.get(out, "status") or "")
    if status not in sn.PLAN:
        out = envelope.set_key(out, "status", "open")
    if envelope.get(out, "schedule") is None:
        out = envelope.set_key(out, "schedule", "serial")
    h1, head, parts = split_plan(body)
    found = dict(parts)
    found["Overview"] = overview_text()
    found.pop("Steps", None)
    found.setdefault("Pre-authorized", NO_PREAUTH)
    rest = [(t, p) for t, p in parts if t not in ORDER and t != "Steps"]
    order = ordered(found) + rest
    lead = f"\n{h1}\n" + (f"\n{text.strip_blank(head)}\n" if head.strip() else "")
    out = envelope.split(out)[0]
    finished = envelope.get(plan_text, "finished")
    return {"text": "---\n" + out + "---\n" + lead + text.join_sections(order),
            "title": str(envelope.get(plan_text, "title") or ""), "goal": text.strip_blank(found.get("Goal", "")),
            "finished": str(finished) if finished else None, "landing": envelope.get(plan_text, "landing")}


def convert(root: Path, folder: Path) -> dict:
    """Rewrite plan.md (and write legacy.md) of the plan `folder`; scaffold its missing ledgers. Returns
    from_legacy's or from_record's dict plus `record` (whether it had front matter) and `scaffolded`."""
    path = folder / "plan.md"
    plan_text = path.read_text()
    record = plan_folder.is_record(plan_text)
    found = from_record(plan_text) if record else from_legacy(root, folder, plan_text)
    path.write_text(found["text"])
    if found.get("legacy"):
        (folder / LEGACY).write_text(found["legacy"])
    values = plan_folder.fields(root, int(folder.name[:4]), found["title"], found["goal"],
                                str(found["landing"] or "manual"))
    found["scaffolded"] = [p.name for p in plan_folder.scaffold(path, values)]
    found["record"] = record
    return found
