"""The day file of the daybook: parse, render, carry-over and the item edits (jot, tick, move).

A day is `{"head": [lines before the first ##], "sections": [section, ...]}`; a section is a dict with `title`,
`role` (today, later, watches, plans, done, or None for an unknown section), `marker` (its first `<!--` line) and
`items` (each a list of lines: the `- ` line and its indented lines); an unknown section keeps its `raw` lines.
Rendering a parsed file gives it back unchanged when it is in the canonical form (jobsearch's files are).
"""
import datetime as dt
import re

ROLES = ("today", "later", "watches", "plans", "done")
CARRIED = ("today", "later", "watches")
MOVABLE = ("today", "later")
TITLES = {
    "en": {"today": "Today", "later": "Later", "watches": "Watches", "plans": "Plans", "done": "Done"},
    "de": {"today": "Heute", "later": "Demnächst", "watches": "Watches", "plans": "Offene Pläne", "done": "Erledigt"},
}
WORDS = {"en": {"since": "since", "done": "done", "head": "Daybook"},
         "de": {"since": "seit", "done": "erledigt", "head": "Daily"}}
WEEKDAYS = {"en": ["Monday", "Tuesday", "Wednesday", "Thursday", "Friday", "Saturday", "Sunday"],
            "de": ["Montag", "Dienstag", "Mittwoch", "Donnerstag", "Freitag", "Samstag", "Sonntag"]}
ROLE_BY_TITLE = {title: role for lang in TITLES.values() for role, title in lang.items()}
MARKER = "<!-- generated by daybook.py: do not edit -->"
OPEN_RE = re.compile(r"^- \[ \] ")
DONE_RE = re.compile(r"^- \[[xX]\] ")
WATCH_RE = re.compile(r"\[watch:([a-z0-9-]+)\]")
SINCE_RE = re.compile(r"\((?:since|seit) (\d{4}-\d{2}-\d{2})\)")


class RefError(ValueError):
    """A reference that names no item or several; `candidates` lists them."""

    def __init__(self, message, candidates):
        super().__init__(message)
        self.candidates = candidates


def section(title, role, marker=None):
    return {"title": title, "role": role, "marker": marker, "items": [], "raw": []}


def is_open(item):
    return bool(OPEN_RE.match(item[0]))


def items_of(lines):
    """Lines -> items; a line that is no item and no continuation stays as an item of its own (never lost)."""
    items = []
    for line in lines:
        if not line.strip():
            continue
        if line.startswith(" ") and items:
            items[-1].append(line)
        else:
            items.append([line])
    return items


def parse(text):
    head, sections = [], []
    for line in text.splitlines():
        if line.startswith("## "):
            title = line[3:].strip()
            sections.append(section(title, ROLE_BY_TITLE.get(title)))
        elif not sections:
            head.append(line)
        elif sections[-1]["role"] is None:
            sections[-1]["raw"].append(line)
        elif line.startswith("<!--") and sections[-1]["marker"] is None and not sections[-1]["items"]:
            sections[-1]["marker"] = line
        elif line.strip():
            sec = sections[-1]
            if line.startswith(" ") and sec["items"]:
                sec["items"][-1].append(line)
            else:
                sec["items"].append([line])
    return {"head": head, "sections": sections}


def render(day):
    lines = list(day["head"])
    for sec in day["sections"]:
        lines.append(f"## {sec['title']}")
        if sec["role"] is None:
            lines += sec["raw"]
            continue
        lines.append("")
        if sec["marker"]:
            lines.append(sec["marker"])
        for item in sec["items"]:
            lines += item
        lines.append("")
    return "\n".join(lines).rstrip("\n") + "\n"


def language(text):
    return "de" if re.search(r"^## Heute\s*$", text or "", re.M) else "en"


def head_lines(date, lang):
    return [f"# {WORDS[lang]['head']} {date.isoformat()} ({WEEKDAYS[lang][date.weekday()]})", ""]


def carry_section(sec):
    """The section as the next day starts it: open items move on, generated content is the owner's to refresh."""
    role = sec["role"]
    if role in CARRIED:
        new = section(sec["title"], role, sec["marker"])
        new["items"] = [list(item) for item in sec["items"] if is_open(item)]
    elif role == "plans":
        new = section(sec["title"], role, MARKER)
    elif role == "done":
        new = section(sec["title"], role)
    else:
        new = section(sec["title"], None)
        first = next((line for line in sec["raw"] if line.strip()), "")
        kept = [first] if first.startswith("<!--") else []
        kept += [line for item in items_of(sec["raw"]) if is_open(item) for line in item]
        new["raw"] = [""] + kept + [""]
    return new


def complete(day, lang):
    """Add every known section the day lacks, after the known sections before it in ROLES' order."""
    sections = day["sections"]
    for i, role in enumerate(ROLES):
        if any(sec["role"] == role for sec in sections):
            continue
        before = [n for n, sec in enumerate(sections) if sec["role"] in ROLES[:i]]
        sections.insert(before[-1] + 1 if before else 0,
                        section(TITLES[lang][role], role, MARKER if role == "plans" else None))
    return day


def carry_over(previous, date, lang):
    """Today's day from the newest earlier one (None: an empty day). Nothing is dropped but ticked items."""
    sections = [carry_section(sec) for sec in previous["sections"]] if previous else []
    return complete({"head": head_lines(date, lang), "sections": sections}, lang)


def first(day, role):
    return next(sec for sec in day["sections"] if sec["role"] == role)


def open_items(day):
    """[(number, section, index, item)] of the open items of today, later and watches, in file order."""
    out = []
    for sec in day["sections"]:
        if sec["role"] in CARRIED:
            for i, item in enumerate(sec["items"]):
                if is_open(item):
                    out.append((len(out) + 1, sec, i, item))
    return out


def find(day, ref):
    items = open_items(day)
    ref = ref.strip()
    if ref.isdigit():
        hits = [it for it in items if it[0] == int(ref)]
    else:
        hits = [it for it in items if ref.lower() in it[3][0].lower()]
    if len(hits) != 1:
        cands = [f"{h[0]}. {h[3][0][6:]}" for h in hits]
        raise RefError(f"'{ref}' matches {len(hits)} open items", cands)
    return hits[0]


def watch_ids(day):
    return {m.group(1) for sec in day["sections"] for item in sec["items"] + items_of(sec["raw"])
            for m in [WATCH_RE.search(item[0])] if m}


def jot(day, text, role, date, lang):
    line = " ".join(text.split())
    first(day, role)["items"].append([f"- [ ] {line} ({WORDS[lang]['since']} {date.isoformat()})"])


def tick(day, ref, now, lang):
    """Move one open item under Done; returns the item and the id of the watch it ends (or None)."""
    _, sec, i, item = find(day, ref)
    sec["items"].pop(i)
    item = list(item)
    item[0] = "- [x] " + item[0][6:] + f" · {WORDS[lang]['done']} {now.strftime('%H:%M')}"
    first(day, "done")["items"].append(item)
    match = WATCH_RE.search(item[0])
    return item, match.group(1) if match else None


def tick_watch(day, watch_id, now, lang):
    """Tick the open item of a watch, if there is one."""
    for number, _, _, item in open_items(day):
        if f"[watch:{watch_id}]" in item[0]:
            return tick(day, str(number), now, lang)[0]
    return None


def move(day, ref, role):
    _, sec, i, item = find(day, ref)
    first(day, role)["items"].append(sec["items"].pop(i))
    return item


def add_watch_items(day, watches, date, lang):
    known = watch_ids(day)
    for watch in watches:
        if watch.get("active", True) is not False and watch.get("id") not in known:
            every = watch.get("every") or watch.get("cron")
            first(day, "watches")["items"].append(
                [f"- [ ] {watch.get('title')} ({every}; {WORDS[lang]['since']} {date.isoformat()}) "
                 f"[watch:{watch['id']}]"])


def item_info(number, sec, item, date):
    text = item[0][6:] if OPEN_RE.match(item[0]) or DONE_RE.match(item[0]) else item[0]
    since = SINCE_RE.search(item[0])
    age = (date - dt.date.fromisoformat(since.group(1))).days if since else None
    watch = WATCH_RE.search(item[0])
    return {"n": number, "section": sec["role"], "text": text, "since": since.group(1) if since else None,
            "age_days": age, "watch": watch.group(1) if watch else None}
