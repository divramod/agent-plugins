def git(*args, cwd):
    subprocess.run(["git", *args], cwd=cwd, check=True, capture_output=True)


class Base(unittest.TestCase):
    def setUp(self):
        self.tmp = Path(tempfile.mkdtemp(prefix="daybook-test-"))
        self.addCleanup(shutil.rmtree, self.tmp, True)
        self.farm = self.tmp / "farm"
        self.farm.mkdir()
        self.env = {k: os.environ.pop(k) for k in ("DAYBOOK_DIR", "DAYBOOK_PLAN_PY") if k in os.environ}
        self.addCleanup(os.environ.update, self.env)
        os.environ["DAYBOOK_PLAN_PY"] = str(self.tmp / "no-plan.py")
        self.addCleanup(os.environ.pop, "DAYBOOK_PLAN_PY", None)

    def run_cli(self, *args, farm_dir=None, code=0):
        out, err = io.StringIO(), io.StringIO()
        with contextlib.redirect_stdout(out), contextlib.redirect_stderr(err):
            got = daybook.main(["--farm", str(farm_dir or self.farm), *args])
        self.assertEqual(got, code, err.getvalue() + out.getvalue())
        return out.getvalue() if code == 0 else err.getvalue()

    def day(self, date, folder="daybook"):
        return (self.farm / folder / f"{date}.md").read_text(encoding="utf-8")

    def write_day(self, date, text, folder="daybook"):
        (self.farm / folder).mkdir(exist_ok=True)
        (self.farm / folder / f"{date}.md").write_text(text, encoding="utf-8")


class CarryOver(Base):
    def test_open_chores_move_on_across_a_gap(self):
        self.write_day("2026-10-10", OLD)
        self.run_cli("--date", "2026-10-13", "show")
        new = self.day("2026-10-13")
        self.assertTrue(new.startswith("# Daybook 2026-10-13 (Tuesday)\n"))
        self.assertIn("- [ ] call the plumber (since 2026-10-08)\n  with the number from the letter\n", new)
        self.assertIn("## Later\n\n- [ ] renew the passport (since 2026-10-01)\n", new)
        self.assertNotIn("water the plants", new)
        self.assertNotIn("pay the rent", new)
        self.assertIn("## Notes\n\n<!-- generated by notes.py: do not edit -->\n- [ ] an open note\n", new)
        self.assertNotIn("a plain note", new)
        self.assertEqual(self.day("2026-10-10"), OLD)

    def test_existing_today_is_never_rebuilt(self):
        self.write_day("2026-10-10", OLD)
        today = "# Daybook 2026-10-11 (Sunday)\n\n## Today\n\n- [ ] my own (since 2026-10-11)\n"
        self.write_day("2026-10-11", today)
        self.run_cli("--date", "2026-10-11", "show")
        text = self.day("2026-10-11")
        self.assertIn("- [ ] my own (since 2026-10-11)", text)
        self.assertNotIn("plumber", text)

    def test_a_jot_before_show_makes_today_first(self):
        self.write_day("2026-10-10", OLD)
        self.run_cli("--date", "2026-10-12", "jot", "buy", "milk")
        text = self.day("2026-10-12")
        self.assertIn("call the plumber", text)
        self.assertIn("- [ ] buy milk (since 2026-10-12)", text)

    def test_a_second_run_the_same_day_loses_and_doubles_nothing(self):
        self.write_day("2026-10-10", OLD)
        self.run_cli("--date", "2026-10-12", "show")
        self.run_cli("--date", "2026-10-12", "jot", "buy milk")
        first = self.day("2026-10-12")
        self.run_cli("--date", "2026-10-12", "show")
        self.assertEqual(self.day("2026-10-12"), first)
        self.assertEqual(first.count("call the plumber"), 1)

    def test_no_chore_is_ever_lost_over_many_days(self):
        jotted = []
        start = dt.date(2026, 10, 1)
        for n in range(8):
            date = (start + dt.timedelta(days=n * 2 + n % 3)).isoformat()
            for k in range(3):
                jotted.append(f"chore {n}-{k}")
                self.run_cli("--date", date, "jot", jotted[-1])
            self.run_cli("--date", date, "tick", "1")
        files = sorted((self.farm / "daybook").glob("*.md"))
        last = files[-1].read_text(encoding="utf-8")
        everything = "".join(f.read_text(encoding="utf-8") for f in files)
        for chore in jotted:
            ticked = f"- [x] {chore} (since" in everything
            self.assertTrue(ticked or f"- [ ] {chore} (since" in last, chore)
        self.assertEqual(sum(f"- [x] {c} (since" in everything for c in jotted), 8)

    def test_first_day_without_earlier_file(self):
        self.run_cli("--date", "2026-10-12", "show")
        text = self.day("2026-10-12")
        for title in ("Today", "Later", "Watches", "Plans", "Done"):
            self.assertIn(f"## {title}\n", text)


class Edits(Base):
    def setUp(self):
        super().setUp()
        for chore in ("call the plumber", "call the bank", "buy milk"):
            self.run_cli("--date", "2026-10-12", "jot", chore)

    def test_tick_by_number_and_by_text(self):
        self.run_cli("--date", "2026-10-12", "tick", "2")
        self.run_cli("--date", "2026-10-12", "tick", "milk")
        text = self.day("2026-10-12")
        done = text.split("## Done")[1]
        self.assertRegex(done, r"- \[x\] call the bank \(since 2026-10-12\) · done \d\d:\d\d")
        self.assertIn("- [x] buy milk", done)
        self.assertIn("- [ ] call the plumber", text.split("## Done")[0])

    def test_an_ambiguous_ref_writes_nothing(self):
        before = self.day("2026-10-12")
        err = self.run_cli("--date", "2026-10-12", "tick", "call", code=2)
        self.assertIn("1. call the plumber", err)
        self.assertIn("2. call the bank", err)
        self.run_cli("--date", "2026-10-12", "tick", "99", code=2)
        self.assertEqual(self.day("2026-10-12"), before)

    def test_move_and_jot_later(self):
        self.run_cli("--date", "2026-10-12", "move", "1", "later")
        self.run_cli("--date", "2026-10-12", "jot", "--later", "paint the door")
        later = self.day("2026-10-12").split("## Later")[1].split("##")[0]
        self.assertIn("call the plumber", later)
        self.assertIn("paint the door", later)

    def test_json(self):
        data = json.loads(self.run_cli("--date", "2026-10-12", "--json", "show"))
        self.assertEqual([i["text"] for i in data["open"]][:1], ["call the plumber (since 2026-10-12)"])
        self.assertEqual(data["open"][0]["n"], 1)
        self.assertEqual(data["open"][0]["section"], "today")
        self.assertEqual(data["open"][0]["age_days"], 0)
        for key in ("farm", "folder", "date", "path", "done", "plans", "watches"):
            self.assertIn(key, data)
        err = json.loads(self.run_cli("--date", "2026-10-12", "--json", "tick", "call", code=2))
        self.assertEqual(len(err["candidates"]), 2)

    def test_where_writes_nothing(self):
        out = self.run_cli("--date", "2026-10-20", "where")
        self.assertIn(str(self.farm / "daybook" / "2026-10-20.md"), out)
        self.assertFalse((self.farm / "daybook" / "2026-10-20.md").exists())

    def test_a_held_lock_ends_with_5(self):
        (self.farm / "daybook" / ".daybook.lock").touch()
        old = farm.LOCK_WAIT
        farm.LOCK_WAIT = 0.2
        self.addCleanup(setattr, farm, "LOCK_WAIT", old)
        self.run_cli("--date", "2026-10-12", "jot", "x", code=5)


class Folder(Base):
    def test_git_farm_excludes_daybook_once_and_tracks_nothing(self):
        git("init", "-q", cwd=self.farm)
        (self.farm / ".gitignore").write_text("*.log\n")
        git("add", ".gitignore", cwd=self.farm)
        git("-c", "user.email=t@t", "-c", "user.name=t", "commit", "-qm", "init", cwd=self.farm)
        self.run_cli("--date", "2026-10-12", "jot", "x")
        self.run_cli("--date", "2026-10-13", "show")
        exclude = (self.farm / ".git" / "info" / "exclude").read_text()
        self.assertEqual(exclude.splitlines().count("/daybook/"), 1)
        self.assertEqual((self.farm / ".gitignore").read_text(), "*.log\n")
        status = subprocess.run(["git", "status", "--short"], cwd=self.farm, capture_output=True, text=True).stdout
        self.assertEqual(status, "")

    def test_a_worktree_writes_the_main_checkouts_daybook(self):
        git("init", "-q", cwd=self.farm)
        git("-c", "user.email=t@t", "-c", "user.name=t", "commit", "-q", "--allow-empty", "-m", "i", cwd=self.farm)
        tree = self.tmp / "07"
        git("worktree", "add", "-q", str(tree), "-b", "07", cwd=self.farm)
        self.run_cli("--date", "2026-10-12", "jot", "from the worktree", farm_dir=tree)
        self.assertIn("from the worktree", self.day("2026-10-12"))
        self.assertFalse((tree / "daybook").exists())

    def test_non_git_folder_and_missing_farm(self):
        self.run_cli("--date", "2026-10-12", "jot", "x")
        self.assertTrue((self.farm / "daybook" / "2026-10-12.md").exists())
        self.run_cli("--date", "2026-10-12", "show", farm_dir=self.tmp / "nope", code=3)

    def test_daybook_dir_overrides(self):
        os.environ["DAYBOOK_DIR"] = str(self.tmp / "elsewhere")
        self.addCleanup(os.environ.pop, "DAYBOOK_DIR", None)
        self.run_cli("--date", "2026-10-12", "jot", "x")
        self.assertTrue((self.tmp / "elsewhere" / "2026-10-12.md").exists())


