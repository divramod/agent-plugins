class Watches(Base):
    def test_add_list_ran_rm(self):
        self.run_cli("--date", "2026-10-12", "watch", "add", "mail", "--title", "Answer from Bob",
                     "--cron", "0 */3 * * *", "--prompt", "Watch mail (daybook/watches.yaml), read-only", "--every",
                     "every 3 h")
        self.assertIn("- [ ] Answer from Bob (every 3 h; since 2026-10-12) [watch:mail]", self.day("2026-10-12"))
        rows = json.loads(self.run_cli("--json", "watch", "list"))["watches"]
        self.assertEqual((rows[0]["id"], rows[0]["active"], rows[0]["due"]), ("mail", True, True))
        self.run_cli("--date", "2026-10-12", "watch", "ran", "mail", "--result", "nothing new")
        row = json.loads(self.run_cli("--json", "watch", "list"))["watches"][0]
        self.assertEqual((row["due"], row["last_result"]), (False, "nothing new"))
        self.run_cli("--date", "2026-10-12", "watch", "rm", "mail")
        self.assertIn("[watch:mail] · done", self.day("2026-10-12").split("## Done")[1])
        self.assertFalse(json.loads(self.run_cli("--json", "watch", "list"))["watches"][0]["active"])
        self.run_cli("--date", "2026-10-13", "show")
        self.assertNotIn("[watch:mail]", self.day("2026-10-13"))

    def test_bad_input(self):
        self.run_cli("watch", "add", "Bad_Id", "--title", "t", "--cron", "* * * * *", "--prompt", "p", code=2)
        self.run_cli("watch", "add", "ok", "--title", "t", "--cron", "* * *", "--prompt", "p", code=2)
        self.run_cli("watch", "rm", "nope", code=2)
        (self.farm / "daybook").mkdir(exist_ok=True)
        (self.farm / "daybook" / "watches.yaml").write_text("watches:\n- id: x\n  prompt: |\n    text\n")
        self.run_cli("show", code=4)

    def test_due(self):
        now = dt.datetime(2026, 10, 14, 10, 30)
        watch = {"cron": "0 0,3,6,9,12,15,18,21 * * *", "last_run": "2026-10-14T08:59:00"}
        self.assertTrue(watchfile.due(watch, now))
        self.assertFalse(watchfile.due(dict(watch, last_run="2026-10-14T09:00:05"), now))
        self.assertFalse(watchfile.due(dict(watch, active=False), now))
        self.assertTrue(watchfile.due({"cron": "0 9 * * *"}, now))
        self.assertEqual(watchfile.latest("30 9 * * 1-5", dt.datetime(2026, 10, 18, 12)),
                         dt.datetime(2026, 10, 16, 9, 30))
        self.assertEqual(watchfile.latest("0 8 13 * 0", dt.datetime(2026, 10, 14, 12)),
                         dt.datetime(2026, 10, 13, 8, 0))
        self.assertIsNone(watchfile.due({"cron": "bad"}, now))


class Yaml(unittest.TestCase):
    def test_fixture_parses_as_pyyaml_and_round_trips(self):
        text = (FIXTURE / "watches.yaml").read_text(encoding="utf-8")
        comments, watches = watchfile.parse(text)
        self.assertEqual(len(watches), 3)
        self.assertIn("Arvid's applications since", watches[0]["prompt"])
        self.assertIn('contains "Ihr Profil verstößt"; free: tell Arvid.\tDone.', watches[2]["prompt"])
        self.assertEqual(watches[2]["cron"], "*/30 9-17 * * 1-5")
        self.assertEqual(watchfile.parse(watchfile.dump(comments, watches)), (comments, watches))
        try:
            import yaml
        except ImportError:
            return
        self.assertEqual(watches, yaml.safe_load(text)["watches"])
        tricky = [{"id": "a", "last_run": "2026-10-14T09:00:00+02:00", "n": "12", "y": "yes", "s": "*/5 * * * *",
                   "q": "it's: here #x", "e": "", "u": None, "line": "two\nlines", "b": True}]
        self.assertEqual(yaml.safe_load(watchfile.dump([], tricky))["watches"], tricky)
        self.assertEqual(watchfile.parse(watchfile.dump([], tricky))[1], tricky)


class Plans(Base):
    def setUp(self):
        super().setUp()
        os.environ["DAYBOOK_PLAN_PY"] = str(PLAN_PY)
        plans = self.farm / "plans"
        table = "| # | Step | Done when | Status |\n|---|---|---|---|\n"
        for slug, rows, front in (("0001-alpha", "| 1 | First | x | done |\n| 2 | Second | y | next |\n", True),
                                  ("0002-beta", "| 1 | Only | x | |\n", False),
                                  ("0003-gamma", "| 1 | Only | x | done |\n", False)):
            (plans / slug).mkdir(parents=True)
            head = f"---\ntype: Plan\nschema: 1\ntitle: \"{slug}\"\nstatus: open\n---\n\n" if front else ""
            (plans / slug / "plan.md").write_text(f"{head}# Plan {slug}\n\n## Steps\n\n{table}{rows}")
        git("init", "-q", cwd=self.farm)
        git("add", "plans", cwd=self.farm)
        git("-c", "user.email=t@t", "-c", "user.name=t", "commit", "-qm", "plans", cwd=self.farm)
        tree = self.tmp / "07"
        git("worktree", "add", "-q", str(tree), "-b", "07", cwd=self.farm)
        (tree / "plans" / "0004-delta").mkdir()
        (tree / "plans" / "0004-delta" / "plan.md").write_text(f"# Plan 0004\n\n{table}| 1 | Build it | x | done |\n"
                                                               "| 2 | Test it | y | |\n| 3 | Ship | z | |\n")
        (tree / "plans" / "CURRENT_PLAN").write_text("0004-delta\n")

    def test_scan(self):
        out = self.run_cli("plans")
        lines = out.splitlines()
        self.assertEqual(lines[0], "- wt 07: 0004-delta (1/3), next 2: Test it")
        self.assertIn("- 0001-alpha (1/2), next 2: Second · `plans/0001-alpha/plan.md`", lines)
        self.assertIn("- 0002-beta (0/1), next 1: Only · `plans/0002-beta/plan.md`", lines)
        self.assertNotIn("gamma", out)
        self.assertFalse((self.farm / "daybook").exists())
        self.run_cli("--date", "2026-10-12", "show")
        plans = self.day("2026-10-12").split("## Plans\n\n")[1].split("##")[0]
        self.assertTrue(plans.startswith(dayfile.MARKER + "\n- wt 07: 0004-delta (1/3)"))

    def test_plan_tool_missing(self):
        os.environ["DAYBOOK_PLAN_PY"] = str(self.tmp / "missing.py")
        self.assertIn("plan.py not found", self.run_cli("plans"))


